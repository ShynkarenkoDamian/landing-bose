import { mkdir, readdir, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const PROJECT_ROOT = process.cwd();
const SOURCE_DIR = path.resolve(PROJECT_ROOT, "src", "assets", "images", "original");
const OUTPUT_DIR = path.resolve(PROJECT_ROOT, "src", "assets", "images", "optimized");
const REPORT_PATH = path.resolve(PROJECT_ROOT, "docs", "figma", "optimized-images.md");
const SOURCE_PATTERN = /\.(jpe?g|png)$/i;
const DEFAULT_WIDTHS = [320, 640, 744, 1260, 1488, 2520];
const SOURCE_WIDTHS = {
    "bose-logo.png": [125, 188, 250, 376, 571],
    "category-headphones-narrow.png": [260, 520, 1040],
    "category-headphones-wide.png": [260, 520, 1040],
    "category-speakers-narrow.png": [260, 520, 1040],
    "category-speakers-wide.png": [260, 520, 1040],
    "category-sunglasses-narrow.png": [260, 520, 1040],
    "category-sunglasses-wide.png": [260, 520, 1040],
    "product-1.png": [160, 320, 392],
    "product-2.png": [160, 320, 392],
    "product-3.png": [160, 320, 392],
};

const kb = (bytes) => (bytes / 1024).toFixed(1);
const formatName = (extension) => (extension === "jpg" ? "JPEG" : extension.toUpperCase());

function assertOutputDirectoryIsManaged() {
    const managedRoot = path.resolve(PROJECT_ROOT, "src", "assets", "images");
    const relativeOutput = path.relative(managedRoot, OUTPUT_DIR);

    if (
        !relativeOutput ||
        relativeOutput.startsWith("..") ||
        path.isAbsolute(relativeOutput) ||
        OUTPUT_DIR === SOURCE_DIR
    ) {
        throw new Error(`Refusing to clear output directory outside the managed image folder: ${OUTPUT_DIR}`);
    }
}

async function removePreviousVariants() {
    try {
        const entries = await readdir(OUTPUT_DIR, { withFileTypes: true });

        for (const entry of entries) {
            if (entry.isFile() && /\.(avif|webp|jpe?g|png)$/i.test(entry.name)) {
                await rm(path.join(OUTPUT_DIR, entry.name));
            }
        }
    } catch (error) {
        if (error.code !== "ENOENT") {
            throw error;
        }
    }
}

async function render(input, outputName, width, fallbackFormat) {
    const base = sharp(input).resize({ width, withoutEnlargement: true });
    const variants = [
        { ext: "avif", image: base.clone().avif({ quality: 50, effort: 4 }) },
        { ext: "webp", image: base.clone().webp({ quality: 76 }) },
        {
            ext: fallbackFormat,
            image:
                fallbackFormat === "png"
                    ? base.clone().png({ compressionLevel: 9 })
                    : base.clone().jpeg({ quality: 78, mozjpeg: true }),
        },
    ];

    const files = [];
    for (const { ext, image } of variants) {
        const file = path.join(OUTPUT_DIR, `${outputName}-${width}.${ext}`);
        await image.toFile(file);
        files.push({ file, extension: ext, width, bytes: (await stat(file)).size });
    }

    return files;
}

function createReport(rows, sourceBytes, outputBytes) {
    const saved = sourceBytes - outputBytes;
    const percent = sourceBytes ? ((saved / sourceBytes) * 100).toFixed(1) : "0.0";
    const tableRows = rows
        .flatMap((row) => row.variants)
        .map(
            (file) =>
                `| \`${path.basename(file.file)}\` | ${formatName(file.extension)} | ${file.width} px | ${kb(file.bytes)} KiB |`,
        )
        .join("\n");

    return `# Generated image variants

Generated by \`npm run images\` from \`src/assets/images/original/\`. No source is upscaled. The category exports have opaque pixels even though their PNG files carry alpha channels, so their fallback is JPEG. Transparent product and logo exports keep PNG fallback. AVIF and WebP are generated for every source.

Widths are selected per source: category photos target 260, 520, and 1040 px; product photos target 160, 320, and 392 px; the logo targets 125, 188, 250, 376, and 571 px. Requested widths are capped at each source's native width. The product widths include 2× of a 160 px card image; the logo widths include 2× of its 125 px and 188 px header sizes.

Source total: ${kb(sourceBytes)} KiB across ${rows.length} files. Generated total: ${kb(outputBytes)} KiB across ${rows.reduce((total, row) => total + row.variants.length, 0)} variants. Size change: ${kb(saved)} KiB (${percent}%).

| File | Format | Width | Size |
| ---- | ------ | ----: | ---: |
${tableRows}
`;
}

async function main() {
    assertOutputDirectoryIsManaged();

    const sources = (await readdir(SOURCE_DIR)).filter((file) => SOURCE_PATTERN.test(file)).sort();
    if (!sources.length) {
        throw new Error(`No source images found in ${SOURCE_DIR}.`);
    }

    await mkdir(OUTPUT_DIR, { recursive: true });
    await removePreviousVariants();

    let sourceTotal = 0;
    let outputTotal = 0;
    const rows = [];

    for (const source of sources) {
        const input = path.join(SOURCE_DIR, source);
        const metadata = await sharp(input).metadata();
        const imageStats = await sharp(input).stats();
        const hasTransparency = metadata.hasAlpha && imageStats.channels[3]?.min < 255;
        const fallbackFormat = hasTransparency ? "png" : "jpg";
        const sourceBytes = (await stat(input)).size;
        const outputName = path.parse(source).name;
        const requestedWidths = SOURCE_WIDTHS[source] ?? DEFAULT_WIDTHS;
        const targetWidths = [
            ...new Set([...requestedWidths, metadata.width].map((width) => Math.min(width, metadata.width))),
        ].sort((left, right) => left - right);
        const variants = [];

        for (const width of targetWidths) {
            variants.push(...(await render(input, outputName, width, fallbackFormat)));
        }

        sourceTotal += sourceBytes;
        outputTotal += variants.reduce((total, file) => total + file.bytes, 0);
        rows.push({ source, sourceWidth: metadata.width, fallbackFormat, variants });
    }

    await writeFile(REPORT_PATH, createReport(rows, sourceTotal, outputTotal), "utf8");
    console.log(
        `Generated ${rows.reduce((total, row) => total + row.variants.length, 0)} variants from ${rows.length} source files.`,
    );
    console.log(`Updated ${path.relative(PROJECT_ROOT, REPORT_PATH)}.`);
}

main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
});
